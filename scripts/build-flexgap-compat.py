"""Generate the flex-gap fallback used by older Tizen TVs (2018 = Tizen 4.0, ~Chromium 56).

Flexbox `gap` only arrived in Chromium 84. This copies every rule that sets `gap`
into app/assets/flexgap-compat.css as a `--fg` custom property (which cascades the
same way), and lists the selectors in app/assets/flexgap-selectors.js. At runtime
assets/flexgap.js turns `--fg` into child margins, only when gap is unsupported.
Re-run after editing app/style.css: python3 scripts/build-flexgap-compat.py
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent
css = re.sub(r'/\*.*?\*/', '', (ROOT / 'app/style.css').read_text(), flags=re.S)


def blocks(text):
    """Yield (prelude, body) for each top-level block."""
    i, depth, start, pre = 0, 0, 0, None
    while i < len(text):
        c = text[i]
        if c == '{':
            if depth == 0:
                pre, start = text[start:i].strip(), i + 1
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                yield pre, text[start:i]
                start = i + 1
        i += 1


def gap_rules(text):
    out = []
    for pre, body in blocks(text):
        if pre.startswith('@media'):
            inner = gap_rules(body)
            if inner:
                out.append((pre, inner))
        elif not pre.startswith('@'):
            m = re.search(r'(?:^|;)\s*gap:\s*([^;]+)', body)
            if m:
                out.append((pre, m.group(1).strip()))
    return out


rules = gap_rules(css)
selectors = []


def emit(items):
    lines = []
    for pre, value in items:
        if isinstance(value, list):
            lines.append(pre + '{' + ''.join(emit(value)) + '}')
        else:
            lines.append(pre + '{--fg:' + value + '}')
            selectors.extend(s.strip() for s in pre.split(','))
    return lines


body = emit(rules)
header = '/* Generated by scripts/build-flexgap-compat.py. Do not edit. */\n'
(ROOT / 'app/assets/flexgap-compat.css').write_text(header + '*{--fg:none}\n' + '\n'.join(body) + '\n')
unique = list(dict.fromkeys(selectors))
(ROOT / 'app/assets/flexgap-selectors.js').write_text(
    header + 'window.CleanFrameFlexGapSelectors = ' + json.dumps(', '.join(unique)) + ';\n')
print('Flex-gap fallback: %d rules, %d selectors' % (len(body), len(unique)))
